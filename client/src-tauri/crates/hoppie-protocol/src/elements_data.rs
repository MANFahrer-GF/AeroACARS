#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn no_duplicate_ids_within_a_table() {
        for table in [
            HOPPIE_UM_TABLE,
            GOLD_UM_TABLE,
            HOPPIE_DM_TABLE,
            GOLD_DM_TABLE,
        ] {
            let mut seen = std::collections::HashSet::new();
            for spec in table {
                assert!(seen.insert(spec.id), "duplicate element id {}", spec.id);
            }
        }
    }

    #[test]
    fn no_duplicate_ids_across_hoppie_and_gold_within_a_direction() {
        let mut seen = std::collections::HashSet::new();
        for spec in HOPPIE_UM_TABLE.iter().chain(GOLD_UM_TABLE.iter()) {
            assert!(seen.insert(spec.id), "duplicate UM id {} across Hoppie/GOLD tables", spec.id);
        }
        let mut seen = std::collections::HashSet::new();
        for spec in HOPPIE_DM_TABLE.iter().chain(GOLD_DM_TABLE.iter()) {
            assert!(seen.insert(spec.id), "duplicate DM id {} across Hoppie/GOLD tables", spec.id);
        }
    }

    #[test]
    fn every_row_direction_matches_its_table() {
        for spec in HOPPIE_UM_TABLE.iter().chain(GOLD_UM_TABLE.iter()) {
            assert_eq!(spec.direction, Direction::Uplink, "{} in a UM table", spec.id);
        }
        for spec in HOPPIE_DM_TABLE.iter().chain(GOLD_DM_TABLE.iter()) {
            assert_eq!(spec.direction, Direction::Downlink, "{} in a DM table", spec.id);
        }
    }

    #[test]
    fn every_template_placeholder_count_matches_declared_placeholders() {
        // Guards against the exact bug the "five template patches"
        // module doc describes: a template with fewer @N markers than
        // declared placeholders silently drops values on resolve().
        for spec in HOPPIE_UM_TABLE
            .iter()
            .chain(GOLD_UM_TABLE.iter())
            .chain(HOPPIE_DM_TABLE.iter())
            .chain(GOLD_DM_TABLE.iter())
        {
            let at_count = (1..=spec.placeholders.len())
                .filter(|n| spec.template.contains(&format!("@{n}")))
                .count();
            assert_eq!(
                at_count,
                spec.placeholders.len(),
                "{}: template {:?} has {} @N markers but {} placeholders declared",
                spec.id,
                spec.template,
                at_count,
                spec.placeholders.len()
            );
        }
    }

    #[test]
    fn gold_table_size_is_the_expected_order_of_magnitude() {
        // Loose sanity bound, not an exact count -- catches a
        // catastrophic extraction regression (e.g. accidentally
        // re-running against a truncated source) without being brittle
        // against a future libcpdlc update adding/removing a handful
        // of rows.
        assert!(GOLD_UM_TABLE.len() > 150, "GOLD_UM_TABLE looks truncated: {} rows", GOLD_UM_TABLE.len());
        assert!(GOLD_DM_TABLE.len() > 60, "GOLD_DM_TABLE looks truncated: {} rows", GOLD_DM_TABLE.len());
    }
}
